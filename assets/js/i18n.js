/* ── MOTOR DE TRADUCCIÓN ─────────────────────────────────── */
const I18N = {
  current: 'es',

  init() {
    // Detectar idioma guardado o preferencia del navegador
    const saved = localStorage.getItem('arc_lang');
    const browser = navigator.language?.startsWith('en') ? 'en' : 'es';
    this.current = saved || browser;
    this.apply();
    this.bindButtons();
  },

  apply() {
    const t = TRANSLATIONS[this.current];
    if (!t) return;

    // Aplicar traducciones a todos los elementos con data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key] === undefined) return;

      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t[key];
      } else if (el.tagName === 'OPTION') {
        el.textContent = t[key];
      } else {
        // Preservar saltos de línea con \n
        el.innerHTML = t[key].replace(/\n/g, '<br>');
      }
    });

    // Actualizar botones de idioma
    document.querySelectorAll('.navbar__lang button').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === this.current);
    });

    // Actualizar atributo lang del HTML para accesibilidad y SEO
    document.documentElement.setAttribute('lang', this.current);

    // Guardar preferencia
    localStorage.setItem('arc_lang', this.current);
  },

  bindButtons() {
    document.querySelectorAll('.navbar__lang button').forEach(btn => {
      btn.addEventListener('click', () => {
        this.current = btn.dataset.lang;
        this.apply();
      });
    });
  },

  t(key) {
    return TRANSLATIONS[this.current]?.[key] || key;
  }
};

// Iniciar cuando el DOM esté listo
document.addEventListener('DOMContentLoaded', () => I18N.init());
